export function filterTierSections(
  audience: AudienceType,
  tierFilter: LicenseTierFilter
): TierSectionMeta[] {
  const all = getTierSections(audience);
  if (tierFilter === "all") return all;
  return all.filter((sec) => sec.id === tierFilter);
}

export function validateDemoRequest(input: {
  fullName: string;
  phone: string;
}): { valid: boolean; error?: string } {
  const name = input.fullName.trim();
  const phone = input.phone.trim();
  if (!name) {
    return { valid: false, error: "Please enter your full name." };
  }
  if (!phone || phone.length < 5) {
    return {
      valid: false,
      error: "Please enter a valid phone or WhatsApp number.",
    };
  }
  return { valid: true };
}
